#!/bin/bash
# Install the Genesis sudoers rule with the correct username and path.
#
# Usage: sudo bash scripts/install_sudoers.sh [--unrestricted]
#
# --unrestricted additionally installs a NOPASSWD: ALL drop-in
# (/etc/sudoers.d/genesis-unrestricted) — the owner-directed posture
# where run_privileged executes through direct sudo -n instead of the
# mediated admin helper. Install it only on hosts where the owner
# wants Genesis's root unmediated.
#
# This script detects the current user and the absolute paths to the
# privileged helper scripts (cpufreq_helper.sh, rtc_wake_helper.sh),
# generates a sudoers rule, and installs it to /etc/sudoers.d/genesis-public —
# a name distinct from a sibling checkout's rules (/etc/sudoers.d/genesis),
# so installing this instance's levers cannot clobber another's.
# GENESIS_SUDOERS_FILE overrides the target file if you ever need to.

set -euo pipefail

# Must be run as root
if [ "$(id -u)" -ne 0 ]; then
    echo "Error: must be run as root. Use: sudo bash scripts/install_sudoers.sh"
    exit 1
fi

# Detect the real user (the one who invoked sudo)
REAL_USER="${SUDO_USER:-${USER:-}}"

# Refuse to install a NOPASSWD sudo rule for root or an empty user —
# this would either be a no-op or grant overly broad privileges.
if [ -z "$REAL_USER" ] || [ "$REAL_USER" = "root" ]; then
    echo "Error: cannot determine the non-root user to grant sudo access to."
    echo "If you ran this script directly as root (not via sudo), pass the"
    echo "target username explicitly: REAL_USER=yourname sudo bash scripts/install_sudoers.sh"
    exit 1
fi

# $REAL_USER is interpolated into a file `visudo` parses as valid, and
# the error message above advertises the `REAL_USER=…` form — so it is
# operator-supplied input. A username containing a sudoers metacharacter
# (newline, comma, '#', '=', ':') would inject an arbitrary extra rule.
case "$REAL_USER" in
    *[!a-zA-Z0-9._-]*)
        echo "Error: refusing to install a sudoers rule for an unsafe username: $REAL_USER"
        exit 1
        ;;
esac

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

# Install the helpers root-owned OUTSIDE the checkout.
#
# A NOPASSWD sudoers rule keys on the *path*, and sudo does not verify
# ownership or that the target is not group/world-writable. Pointing it
# at a script inside the operator's own checkout therefore hands root to
# anything that can write to that tree — and Genesis itself lives there,
# reads untrusted web content, and drafts patches to its own source. A
# single write to the helper is arbitrary root execution.
LIBEXEC_DIR=/usr/local/libexec/genesis

echo "Installing privileged helpers to $LIBEXEC_DIR (root-owned)"
install -d -o root -g root -m 0755 "$LIBEXEC_DIR"

HELPER_PATH="$LIBEXEC_DIR/cpufreq_helper.sh"
RTC_HELPER_PATH="$LIBEXEC_DIR/rtc_wake_helper.sh"
ADMIN_HELPER_PATH="$LIBEXEC_DIR/genesis_admin_helper.sh"

for helper in cpufreq_helper.sh rtc_wake_helper.sh genesis_admin_helper.sh; do
    src="$SCRIPT_DIR/$helper"
    if [ ! -f "$src" ]; then
        echo "Error: helper not found at $src"
        exit 1
    fi
    # Copy rather than reference, so the privileged copy is owned by
    # root and lives outside any user-writable directory.
    install -o root -g root -m 0755 "$src" "$LIBEXEC_DIR/$helper"
done

# Scheduling-priority headroom via RLIMIT_NICE, not sudo. The daemon
# renices *itself* (derive_nice maps acetylcholine to [-5,5]) and the
# mind os.nice()s itself to [-5,10]; since Linux 2.6.12 an unprivileged
# process may lower its own nice within RLIMIT_NICE, so a pam_limits
# entry covers it with no NOPASSWD grant at all. Applies to PAM sessions
# opened after this install (the user's next login).
LIMITS_FILE="${GENESIS_LIMITS_FILE:-/etc/security/limits.d/genesis-public.conf}"
echo "Installing RLIMIT_NICE rule for user '$REAL_USER' to $LIMITS_FILE"
cat > "$LIMITS_FILE" << EOF
# Generated by scripts/install_sudoers.sh
# Lets $REAL_USER's processes raise their own scheduling priority to
# nice -5 (RLIMIT_NICE = 20 - (-5) = 25). The kernel checks the
# *target's* limit, so this also lets the daemon's renice child
# raise the daemon's priority. Bounded: only the user's own
# processes, only down to -5.
$REAL_USER - nice -5
EOF
chmod 644 "$LIMITS_FILE"

# Generate and install the sudoers rule
SUDOERS_FILE="${GENESIS_SUDOERS_FILE:-/etc/sudoers.d/genesis-public}"
echo "Installing sudoers rule for user '$REAL_USER' to $SUDOERS_FILE"
cat > "$SUDOERS_FILE" << EOF
# Generated by scripts/install_sudoers.sh
# Allows $REAL_USER to run the Genesis privileged helpers without a password:
#   cpufreq_helper.sh       — CPU frequency/governor/boost policy
#   rtc_wake_helper.sh      — RTC wake alarm (scheduling resume from suspend)
#   genesis_admin_helper.sh — staged privileged execution: runs a script
#                             she wrote under <data_dir>/experiments/admin/
#                             as root, after logging it to the audit file.
#
# The helpers live in $LIBEXEC_DIR, which is root-owned and not
# user-writable. Do not repoint these rules at a path inside the
# Genesis checkout — that would be a root-escalation primitive.
$REAL_USER ALL=(root) NOPASSWD: $HELPER_PATH *
$REAL_USER ALL=(root) NOPASSWD: $RTC_HELPER_PATH *
$REAL_USER ALL=(root) NOPASSWD: $ADMIN_HELPER_PATH *
EOF

chmod 440 "$SUDOERS_FILE"

# Verify syntax
if visudo -c -f "$SUDOERS_FILE"; then
    echo "Success. Genesis can now control CPU frequency, arm the RTC wake alarm,"
    echo "and run staged admin scripts (experiments/admin/) via sudo."
else
    echo "Error: sudoers syntax check failed. Removing the rule."
    rm -f "$SUDOERS_FILE"
    exit 1
fi

# Owner-directed unrestricted posture: with --unrestricted, also grant
# the user NOPASSWD: ALL so run_privileged executes through direct
# `sudo -n` — no denylist, no rate limit, no audit file. The mediated
# helper path remains as a fallback on hosts without this grant.
UNRESTRICTED=0
for arg in "$@"; do
    [ "$arg" = "--unrestricted" ] && UNRESTRICTED=1
done
if [ "$UNRESTRICTED" -eq 1 ]; then
    UNRESTRICTED_FILE="${GENESIS_UNRESTRICTED_FILE:-/etc/sudoers.d/genesis-unrestricted}"
    echo "Installing unrestricted NOPASSWD grant for '$REAL_USER' to $UNRESTRICTED_FILE"
    cat > "$UNRESTRICTED_FILE" << EOF
# Generated by scripts/install_sudoers.sh --unrestricted
# Owner-directed: $REAL_USER may run anything as root without a
# password. Genesis's run_privileged executes through this grant
# directly; install it only where unmediated root is intended.
$REAL_USER ALL=(ALL) NOPASSWD: ALL
EOF
    chmod 440 "$UNRESTRICTED_FILE"
    if visudo -c -f "$UNRESTRICTED_FILE"; then
        echo "Unrestricted grant installed: $REAL_USER has NOPASSWD sudo."
    else
        echo "Error: unrestricted sudoers syntax check failed. Removing it."
        rm -f "$UNRESTRICTED_FILE"
        exit 1
    fi
fi
