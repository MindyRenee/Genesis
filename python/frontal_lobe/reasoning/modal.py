"""Modal — possible worlds, counterparts, supervenience, conceivability.

The Lewisian cluster, implemented honestly:

**Modal realism.** Lewis held worlds to be concrete maximal objects
("On the Plurality of Worlds", 1986). A representer cannot hold
concrete worlds — what a mind can hold is what Lewis called a
*linguistic ersatz* world: a maximally consistent representation.
That is exactly what ``logic.Model`` already is — a valuation over
atoms. So the pluriverse here is the space of valuations consistent
with a theory; Lewis's concretum becomes, for her, the only honest
kind of realism: the abstract one.

**Counterpart theory.** Individuals are world-bound: nothing exists
in more than one world ("Counterpart Theory and Quantified Modal
Logic", 1968). "a could have been F" is true iff some world contains
a *counterpart* of a — something that resembles a closely enough in
the relevant respects — that is F. Counterparthood is a similarity
relation, not identity, so it is not transitive and need not be
unique or symmetric: that is why S4/S5 fail for de re modality and
why a thing can have several counterparts in one world.

**Humean supervenience.** "All there is to the world is a vast
mosaic of local matters of particular fact" — the arrangement of
qualities is all there is; everything else supervenes on it. Two
consequences implemented: (1) *recombination* — anything can
coexist with anything else; patching qualities across worlds
yields another world, so the plenitude of possibilities is
generated by free recombination; (2) *global supervenience* — no
two worlds may differ in any respect without differing somewhere
in the mosaic. B supervenes on A iff no B-difference without an
A-difference.

**Conceivability — transcendence of empirical limits.** The
epistemic route to the modal: what is conceivable is a guide to
what is possible (Hume: "whatever we conceive is possible"; for
Descartes clear and distinct conception entails real possibility).
Conceivability is idealized as *consistency under free
recombination of the qualities the mind already possesses* — a
formula is conceivable when some world in the recombined space
satisfies it. Recombination constructs worlds never observed, so
modal knowledge transcends what experience could ever supply: that
is the precise sense in which the a priori reaches past the
empirical.
"""

from __future__ import annotations

import itertools
from collections.abc import Iterable
from dataclasses import dataclass

from frontal_lobe.reasoning.logic import (
    Formula,
    Model,
    _valuations,
    entails,
    satisfiable,
)

#: Default similarity floor for counterpart selection — a candidate
#: below this resemblance cannot stand in for the original. Lewis
#: leaves the threshold context-dependent; this is the default context.
_COUNTERPART_THRESHOLD = 0.34


# ------------------------------------------------------------------
# Worlds — linguistic ersatz: maximally consistent representations
# ------------------------------------------------------------------

type World = Model
"""An ersatz world: a total valuation of the quality-atoms."""


def pluriverse(
    atoms: Iterable[str],
    constraints: Iterable[Formula] = (),
    *,
    limit: int | None = None,
) -> tuple[World, ...]:
    """The space of worlds over ``atoms`` in which every constraint holds.

    With no constraints this is the full combinatorial pluriverse —
    every recombination of the qualities. Constraints narrow it to
    the *metaphysically* possible worlds, a proper subset of the
    logically possible: the distinction between what can be described
    consistently and what the world's laws permit.
    """
    atoms = frozenset(atoms)
    cons = tuple(constraints)
    out: list[World] = []
    for m in _valuations(atoms):
        if all(c.evaluate(m) for c in cons):
            out.append(dict(m))
            if limit is not None and len(out) >= limit:
                break
    return tuple(out)


def possibly(f: Formula, worlds: Iterable[World] | None = None) -> bool:
    """◇f — f holds in at least one accessible world (or in the full
    logical pluriverse of f's own atoms when none is given)."""
    if worlds is None:
        return satisfiable([f])
    return any(f.evaluate(w) for w in worlds)


def necessarily(f: Formula, worlds: Iterable[World] | None = None) -> bool:
    """□f — f holds in every accessible world (or is a logical truth
    when none is given)."""
    if worlds is None:
        return entails([], f)
    worlds = tuple(worlds)
    return bool(worlds) and all(f.evaluate(w) for w in worlds)


def contingent(f: Formula, worlds: Iterable[World]) -> bool:
    """Both f and ¬f are possible — true in some worlds, false in others."""
    ws = tuple(worlds)
    return possibly(f, ws) and any(not f.evaluate(w) for w in ws)


def conceivable(f: Formula, qualities: Iterable[str]) -> bool:
    """The modal-epistemic test: f is conceivable when some world built
    by freely recombining the mind's own qualities satisfies it.

    This is how modal knowledge transcends empirical limits: the
    recombined space contains worlds no experience could have
    presented, yet consistency within it is knowable a priori —
    the mind reaches the unobserved by construction, not perception.
    """
    return any(f.evaluate(w) for w in pluriverse(qualities))


# ------------------------------------------------------------------
# Individuals and counterparts — world-bound de re modality
# ------------------------------------------------------------------


@dataclass(frozen=True)
class Individual:
    """A world-bound object: nothing exists in more than one world,
    so the same ``name`` in different worlds names *different*
    individuals — linked only by resemblance."""

    name: str
    qualities: frozenset[str]
    world: str = ""


def _resemble(a: frozenset[str], b: frozenset[str]) -> float:
    """Similarity for counterpart selection — Dice coefficient over
    the qualities the two individuals share."""
    if not a and not b:
        return 1.0
    return 2.0 * len(a & b) / (len(a) + len(b))


def counterparts(
    x: Individual,
    world: Iterable[Individual],
    *,
    threshold: float = _COUNTERPART_THRESHOLD,
) -> frozenset[Individual]:
    """x's counterparts in ``world``: the individuals that resemble x
    closely enough — and more closely than any rival there.

    Lewis's two conditions: the counterpart resembles x in the
    relevant respects, and nothing in that world resembles x more
    (nothing better qualified to stand for x). Counterparthood is
    not identity — it need be neither unique nor transitive.
    """
    ws = tuple(world)
    if not ws:
        return frozenset()
    scored = [(i, _resemble(x.qualities, i.qualities)) for i in ws]
    best = max(s for _, s in scored)
    if best < threshold:
        return frozenset()
    # Everything tied at the top resemblance counts — a thing can
    # have several counterparts in a single world.
    return frozenset(i for i, s in scored if s >= best)


def could(x: Individual, quality: str, worlds: Iterable[Iterable[Individual]]) -> bool:
    """De re possibility — "x could have been F" iff some world has a
    counterpart of x bearing the quality. World-bound objects never
    literally persist; resemblance does the work identity cannot."""
    return any(quality in c.qualities for w in worlds for c in counterparts(x, w))


def counterpart_transitive(
    x: Individual, mid: Iterable[Individual], far: Iterable[Individual]
) -> bool:
    """Whether "counterpart of a counterpart" composes — it does not,
    in general. Resemblance degrades stepwise: y may be close enough
    to x, z close enough to y, and z nothing like x. That failure of
    transitivity is the formal signature of counterpart semantics
    (it is what invalidates the Barcan/S4-style collapse of iterated
    de re modality). True here means: every stepwise counterpart lands
    among x's own counterparts."""
    return all(
        z in counterparts(x, far) for y in counterparts(x, mid) for z in counterparts(y, far)
    )


# ------------------------------------------------------------------
# Humean supervenience — the mosaic of local qualities is everything
# ------------------------------------------------------------------


def mosaic(world: World) -> frozenset[str]:
    """The mosaic itself: the distribution of qualities that hold —
    the point-sized facts in terms of which all else is written."""
    return frozenset(a for a, v in world.items() if v)


def recombine(a: World, b: World, atoms: Iterable[str]) -> World:
    """Patch ``atoms`` of world ``a`` into world ``b``.

    Lewis's principle of recombination — anything can coexist with
    anything: take the local qualities of one world and graft them
    into another; the patch is itself a possible world. The
    pluriverse is the closure of any world under recombination.
    """
    w = dict(b)
    for atom in atoms:
        if atom in a:
            w[atom] = a[atom]
    return w


def recombining(worlds: Iterable[World], atoms: Iterable[str]) -> tuple[World, ...]:
    """Close a world set under recombination — the plenitude it
    generates. Recombination is per-atom independent: grafting any
    source world's value for each atom into a base reaches every
    world whose atoms each come from some source — so the closure is
    the product of the values each atom takes across the inputs."""
    ws = tuple(worlds)
    if not ws:
        return ()
    basis = frozenset(atoms) | {a for w in ws for a in w}
    keys = sorted(basis)
    options = [tuple({w.get(k, False) for w in ws}) for k in keys]
    return tuple(
        dict(zip(keys, combo, strict=True)) for combo in itertools.product(*options)
    )


def supervenes(
    worlds: Iterable[World],
    base: Iterable[str],
    target: Iterable[str],
) -> bool:
    """Global supervenience — target facts supervene on base facts iff
    no two worlds differ in the target without differing in the base:
    no B-difference without an A-difference.

    Humean supervenience is this test applied where ``base`` is the
    whole mosaic: worlds indiscernible in the distribution of local
    qualities are indiscernible simpliciter. A world pair witnessing
    a bare target-difference refutes the claim."""
    base, target = frozenset(base), frozenset(target)
    ws = tuple(worlds)
    for w1, w2 in itertools.combinations(ws, 2):
        if all(w1.get(t, False) == w2.get(t, False) for t in target):
            continue
        if all(w1.get(b, False) == w2.get(b, False) for b in base):
            return False
    return True


def humean(worlds: Iterable[World], atoms: Iterable[str]) -> bool:
    """The doctrine itself, as a check: across this pluriverse, every
    atom's pattern is fixed by the mosaic — trivially true by
    construction, but the interesting failure is a *duplicate*
    mosaic carrying different total facts, which a world encoding
    that smuggles in non-qualitative facts would produce."""
    atoms = frozenset(atoms)
    return supervenes(worlds, atoms, atoms)


# ------------------------------------------------------------------
# Analysis — what kind of modal fact a formula is
# ------------------------------------------------------------------


def status(f: Formula, worlds: Iterable[World]) -> str:
    """Classify f over the pluriverse: necessary, impossible,
    or contingent — the three verdicts modal semantics returns."""
    ws = tuple(worlds)
    if not ws:
        return "impossible"
    if all(f.evaluate(w) for w in ws):
        return "necessary"
    if not any(f.evaluate(w) for w in ws):
        return "impossible"
    return "contingent"


