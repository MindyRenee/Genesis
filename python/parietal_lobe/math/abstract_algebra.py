"""Abstract algebra — the words for structure itself.

A permutation is a move: "(1 2 3)(4 5)" is read, composed, and
answered in cycle notation. The faculty's home truth is the one
the cube taught: the order of a move is the length of its closed
orbit — repeat it `order` times and every point comes home.
"u then d, four times" is a sentence about group order.

The machine half is ``src/math/abstract_algebra.rs``: Permutation,
composition, cycles, sign, generated subgroups, Z_n. Here: the
cycle words and the group's reply.
"""

from __future__ import annotations

import math
import re
from dataclasses import dataclass, field
from typing import Any


@dataclass(frozen=True)
class GroupResult:
    """The outcome of a group-theoretic question."""

    operation: str
    input: str
    output: str
    ok: bool
    error: str = ""
    data: dict[str, Any] = field(default_factory=dict)


_CYCLE_TOKEN = re.compile(r"\(([^()]*)\)")


def parse_perm(text: str, n: int | None = None) -> list[int] | None:
    """Parse cycle notation "(0 1 2)(3 4)" into an image list.

    Elements are 0-based; elements never named stay fixed.
    Returns None when the text isn't permutation-shaped.
    """
    cycles = _CYCLE_TOKEN.findall(text)
    if not cycles:
        return None
    elems: list[int] = []
    parsed: list[list[int]] = []
    for c in cycles:
        try:
            cyc = [int(t) for t in c.split()]
        except ValueError:
            return None
        if len(set(cyc)) != len(cyc):
            return None
        parsed.append(cyc)
        elems.extend(cyc)
    if n is None:
        n = max(elems, default=-1) + 1
    if n < 0 or len(set(elems)) != len(elems) or any(e < 0 or e >= n for e in elems):
        return None
    image = list(range(n))
    for cyc in parsed:
        for i, x in enumerate(cyc):
            image[x] = cyc[(i + 1) % len(cyc)]
    return image


def render_cycles(image: list[int]) -> str:
    """Image list back to cycle notation, fixed points dropped."""
    seen = [False] * len(image)
    parts: list[str] = []
    for s in range(len(image)):
        if seen[s]:
            continue
        cyc = [s]
        seen[s] = True
        x = image[s]
        while x != s:
            cyc.append(x)
            seen[x] = True
            x = image[x]
        if len(cyc) > 1:
            parts.append("(" + " ".join(map(str, cyc)) + ")")
    return "".join(parts) or "e"


def compose(p: list[int], q: list[int]) -> list[int] | None:
    """p then q: x ↦ q[p[x]] — moves read left to right."""
    if len(p) != len(q):
        return None
    return [q[p[x]] for x in range(len(p))]


def inverse(p: list[int]) -> list[int]:
    inv = [0] * len(p)
    for i, j in enumerate(p):
        inv[j] = i
    return inv


def cycles_of(p: list[int]) -> list[list[int]]:
    seen = [False] * len(p)
    out = []
    for s in range(len(p)):
        if seen[s]:
            continue
        cyc = [s]
        seen[s] = True
        x = p[s]
        while x != s:
            cyc.append(x)
            seen[x] = True
            x = p[x]
        out.append(cyc)
    return out


def order_of(p: list[int]) -> int:
    """Order = lcm of cycle lengths — the closed orbit's size."""
    return math.lcm(*(len(c) for c in cycles_of(p)))


def sign_of(p: list[int]) -> int:
    """+1 even, -1 odd — a k-cycle costs k-1 transpositions."""
    return -1 if sum(len(c) - 1 for c in cycles_of(p)) % 2 else 1


def orbit_of(p: list[int], x: int) -> list[int] | None:
    """p^k(x) until it returns — the point's journey home."""
    if x >= len(p):
        return None
    out = [x]
    y = p[x]
    while y != x:
        out.append(y)
        y = p[y]
    return out


def generated(generators: list[list[int]], cap: int = 512) -> list[list[int]] | None:
    """The subgroup the moves generate — closure under then-ing,
    honestly capped."""
    if not generators:
        return []
    n = len(generators[0])
    if any(len(g) != n for g in generators):
        return None
    e = list(range(n))
    seen = {tuple(e)}
    group = [e]
    queue = list(generators)
    while queue:
        g = queue.pop()
        if tuple(g) in seen:
            continue
        if len(group) >= cap:
            return None
        for h in list(group):
            for nxt in (compose(g, h), compose(h, g)):
                if nxt and tuple(nxt) not in seen:
                    queue.append(nxt)
        seen.add(tuple(g))
        group.append(g)
    return group


_GROUP_WORD = re.compile(
    r"\b(?:permutation|cycle|cycles|transposition|symmetric group|"
    r"order of|orbit|sign of|parity|subgroup|generated by|"
    r"homomorphism|isomorphism|cayley)\b",
    re.IGNORECASE,
)


def looks_like_group(text: str) -> bool:
    """Whether the text asks about permutations or groups.

    True for "order of (1 2 3)", "compose (1 2)(3) with (2 3)",
    "sign of that permutation" — and bare cycle notation is
    permutation-shaped on its own.
    """
    return bool(_GROUP_WORD.search(text) or _CYCLE_TOKEN.search(text))


def order_text(text: str) -> GroupResult:
    """ "order of (1 2 3)(4 5)" -> 6 — lcm(3, 2)."""
    p = parse_perm(text)
    if p is None:
        return GroupResult("order", text, "", False, "could not read the permutation")
    o = order_of(p)
    cyc = "·".join(str(len(c)) for c in cycles_of(p))
    return GroupResult(
        "order",
        text,
        f"{o} — cycles of length {cyc}, the orbit closes after {o} repetitions",
        True,
        data={"order": o},
    )


def compose_text(left: str, right: str) -> GroupResult:
    """ "compose (0 1 2) with (1 2)" — left then right."""
    p, q = parse_perm(left), parse_perm(right)
    if p is None or q is None:
        return GroupResult(
            "compose", f"{left} then {right}", "", False, "could not read a permutation"
        )
    n = max(len(p), len(q))
    p += list(range(len(p), n))
    q += list(range(len(q), n))
    out = compose(p, q)
    assert out is not None
    return GroupResult(
        "compose", f"{left} then {right}", render_cycles(out), True, data={"image": out}
    )


def describe_text(text: str) -> GroupResult:
    """Full portrait: cycles, order, sign, and whether the move
    brings everything home."""
    p = parse_perm(text)
    if p is None:
        return GroupResult("describe", text, "", False, "could not read the permutation")
    cyc = cycles_of(p)
    o = order_of(p)
    sgn = "even" if sign_of(p) == 1 else "odd"
    fixed = sum(1 for c in cyc if len(c) == 1)
    out = (
        f"{render_cycles(p)}: {len([c for c in cyc if len(c) > 1])} moving cycles, "
        f"order {o}, {sgn} parity, {fixed} fixed point{'s' if fixed != 1 else ''}"
    )
    return GroupResult(
        "describe", text, out, True, data={"cycles": cyc, "order": o, "sign": sign_of(p)}
    )
