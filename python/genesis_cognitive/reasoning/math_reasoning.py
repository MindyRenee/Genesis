"""Mathematical reasoning engine for Genesis.

This module gives Genesis the ability to DO mathematics, not just know
about it. It provides four capabilities:

1. **Computation** — parse and evaluate arithmetic expressions
2. **Symbolic manipulation** — solve equations by applying
   transformation rules
3. **Proof construction** — verify statements by computation,
   expansion, and templated proofs
4. **Discovery** — generate examples, detect patterns, form and test
   conjectures

## Architecture: computational substrate with configurable rules

The engines (parser, evaluator, solver, discovery) are code — they
are the "hardware" of mathematical reasoning. The RULES they apply
(commutativity, identity, balance, quadratic formula) can be either
hardcoded (default, backward compatible) or gated by the concept
network via ``MathRuleRegistry``.

When ``try_math()`` is called with a concept network, it builds a
``MathRuleRegistry`` that checks which math concepts Genesis has
learned. Only rules whose corresponding concepts exist in the network
(with sufficient confidence) are applied. This means training Genesis
on "the additive identity says that a + 0 = a" enables that rule in
the simplifier.

Without a concept network, all rules are enabled (backward compatible).

## What's genuine vs templated

- **Computation** (parser + evaluator): genuine — parses and evaluates
  real expressions with operator precedence, functions, variables.
- **Equation solving**: genuine — extracts polynomial coefficients,
  applies the quadratic formula, handles complex roots.
- **Discovery**: genuine — generates primes (Sieve of Eratosthenes),
  verifies parity/Goldbach/twin-prime patterns by actual computation.
- **Proof by computation**: genuine — evaluates both sides of an
  equation and checks equality.
- **Proof by expansion**: genuine — expands and collects terms on
  both sides, checks structural equality.
- **Even/odd proofs**: templated — hardcoded proof steps, not
  generated by a proof search algorithm.
- **Induction proof**: templated — hardcoded for the specific case
  ``1 + 2 + ... + n = n(n+1)/2``.
"""

