def collect_variables(node: Any) -> set[str]:
    """Find all variable names in an expression tree."""
    if isinstance(node, Var):
        return {node.name}
    if isinstance(node, BinOp):
        return collect_variables(node.left) | collect_variables(node.right)
    if isinstance(node, UnaryOp):
        return collect_variables(node.operand)
    if isinstance(node, FuncCall):
        result: set[str] = set()
        for arg in node.args:
            result |= collect_variables(arg)
        return result
    return set()


def substitute(node: Any, env: dict[str, Any]) -> Any:
    """Substitute variables in an expression tree with values/expressions."""
    if isinstance(node, Num):
        return node
    if isinstance(node, Var):
        if node.name in env:
            val = env[node.name]
            if isinstance(val, (int, float)):
                return Num(val)
            return val
        return node
    if isinstance(node, BinOp):
        return BinOp(node.op, substitute(node.left, env), substitute(node.right, env))
    if isinstance(node, UnaryOp):
        return UnaryOp(node.op, substitute(node.operand, env))
    if isinstance(node, FuncCall):
        return FuncCall(node.name, [substitute(a, env) for a in node.args])
    return node


# ─── Math rule registry ────────────────────────────────────────

# All available simplification rules. When no concept network is
# provided, all rules are enabled (backward compatible).
_ALL_RULES: frozenset[str] = frozenset(
    {
        "additive_identity",
        "additive_inverse",
        "subtract_zero",
        "subtract_self",
        "multiplicative_zero",
        "multiplicative_identity",
        "multiplicative_inverse",
        "divide_identity",
        "divide_zero",
        "divide_self",
        "power_zero",
        "power_one",
        "zero_power",
        "one_power",
        "constant_fold",
    }
)

# Mapping from concept network concept names to rule names.
# If a concept with one of these names exists in the concept network
# (with confidence >= 0.3), the corresponding rule is enabled.
_CONCEPT_TO_RULE: dict[str, str] = {
    "additive identity": "additive_identity",
    "additive inverse": "additive_inverse",
    "subtract zero": "subtract_zero",
    "subtract self": "subtract_self",
    "multiplicative zero": "multiplicative_zero",
    "multiplicative identity": "multiplicative_identity",
    "multiplicative inverse": "multiplicative_inverse",
    "divide identity": "divide_identity",
    "divide zero": "divide_zero",
    "divide self": "divide_self",
    "power zero": "power_zero",
    "power one": "power_one",
    "zero power": "zero_power",
    "one power": "one_power",
    "constant folding": "constant_fold",
    # Higher-level concepts that imply multiple rules
    "commutative property": "constant_fold",  # commutativity enables reordering
    "algebraic identity": "constant_fold",
}

# Rules that are always enabled regardless of the concept network,
# because they're fundamental to the parser/evaluator working at all.
_BASE_RULES: frozenset[str] = frozenset({"constant_fold"})


class MathRuleRegistry:
    """Registry of math rules enabled based on the concept network.

    This bridges the concept network (Genesis's learned knowledge) and
    the math engine (the computational substrate). Rules are enabled
    when Genesis has learned the corresponding concept.

    Usage:
        registry = MathRuleRegistry.from_concept_network(network)
        result = simplify(expr, registry.enabled_rules)
    """

    def __init__(self, enabled_rules: set[str] | None = None) -> None:
        """Initialize the registry, enabling all rules by default or a custom subset."""
        self.enabled_rules: set[str] = set(enabled_rules) if enabled_rules else set(_ALL_RULES)

    def has_rule(self, name: str) -> bool:
        """Return True if *name* is in the enabled rule set."""
        return name in self.enabled_rules

    @classmethod
    def from_concept_network(cls, network: Any) -> MathRuleRegistry:
        """Build a rule registry from concepts in the network.

        A rule is enabled if:
        1. It's a base rule (always enabled), OR
        2. A concept with the corresponding name exists in the network
           with confidence >= 0.3

        If no math concepts are found in the network at all, all rules
        are enabled (backward compatible — the engine assumes a
        pre-trained network or standalone usage).
        """
        enabled: set[str] = set(_BASE_RULES)
        found_any_math = False

        for concept_name, rule_name in _CONCEPT_TO_RULE.items():
            concept = network.get_concept(concept_name)
            if concept is not None and concept.confidence >= 0.3:
                enabled.add(rule_name)
                found_any_math = True

        # If no math concepts were found, enable all rules (backward compat)
        if not found_any_math:
            return cls()  # all rules

        return cls(enabled)


def simplify(node: Any, enabled_rules: set[str] | None = None) -> Any:
    """Simplify an expression tree by applying algebraic identities.

    Parameters:
        node: The AST node to simplify.
        enabled_rules: Optional set of rule names to apply. If None,
            all rules are enabled (backward compatible). If provided,
            only rules whose names are in the set are applied.

    Rule names:
        - "additive_identity": a + 0 = a, 0 + a = a
        - "additive_inverse": a + (-a) = 0, (-a) + a = 0
        - "subtract_zero": a - 0 = a
        - "subtract_self": a - a = 0
        - "multiplicative_zero": a * 0 = 0, 0 * a = 0
        - "multiplicative_identity": a * 1 = a, 1 * a = a
        - "multiplicative_inverse": a * (-1) = -a, (-1) * a = -a
        - "divide_identity": a / 1 = a
        - "divide_zero": 0 / a = 0
        - "divide_self": a / a = 1
        - "power_zero": a ^ 0 = 1
        - "power_one": a ^ 1 = a
        - "zero_power": 0 ^ a = 0 (a > 0)
        - "one_power": 1 ^ a = 1
        - "constant_fold": evaluate numeric subexpressions

    This makes the simplifier's rule set configurable. The
    ``MathRuleRegistry.from_concept_network`` method builds the
    enabled_rules set from concepts in the concept network, so
    that rules Genesis has learned are applied and rules it
    hasn't learned are skipped.
    """
    if enabled_rules is None:
        enabled_rules = set(_ALL_RULES)

    if isinstance(node, (Num, Var)):
        return node

    if isinstance(node, UnaryOp):
        operand = simplify(node.operand, enabled_rules)
        if isinstance(operand, Num):
            if node.op == "-":
                return Num(-operand.value)
            return operand
        return UnaryOp(node.op, operand)

    if isinstance(node, FuncCall):
        args = [simplify(a, enabled_rules) for a in node.args]
        # If all args are numeric, evaluate
        if "constant_fold" in enabled_rules and all(isinstance(a, Num) for a in args):
            try:
                result = evaluate(FuncCall(node.name, args))
                return Num(result)
            except EvalError as e:
                logger.debug(repr(e))
        return FuncCall(node.name, args)

    if isinstance(node, BinOp):
        left = simplify(node.left, enabled_rules)
        right = simplify(node.right, enabled_rules)

        # If both sides are numeric, evaluate
        if "constant_fold" in enabled_rules and isinstance(left, Num) and isinstance(right, Num):
            try:
                result = evaluate(BinOp(node.op, left, right))
                return Num(result)
            except EvalError as e:
                logger.debug(repr(e))

        # Algebraic identities — each guarded by its rule name
        simplified = _apply_binop_identities(node.op, left, right, enabled_rules)
        if simplified is not None:
            return simplified
        return BinOp(node.op, left, right)

    return node


def _apply_binop_identities(
    op: str, left: Any, right: Any, enabled_rules: set[str]
) -> Any | None:
    """Apply algebraic identity rules to a binary operation.

    Returns the simplified node if an identity matched, or None to
    signal that no identity applied (caller should rebuild the BinOp).
    Each identity is guarded by its rule name in ``enabled_rules``.
    """
    handlers = {
        "+": _identity_add,
        "-": _identity_sub,
        "*": _identity_mul,
        "/": _identity_div,
        "^": _identity_pow,
    }
    handler = handlers.get(op)
    if handler is None:
        return None
    return handler(left, right, enabled_rules)


def _identity_add(left: Any, right: Any, enabled_rules: set[str]) -> Any | None:
    """Algebraic identities for addition: a+0, 0+a, a+(-a), (-a)+a."""
    if "additive_identity" in enabled_rules:
        # a + 0 = a
        if isinstance(right, Num) and right.value == 0:
            return left
        # 0 + a = a
        if isinstance(left, Num) and left.value == 0:
            return right
    if "additive_inverse" in enabled_rules:
        # a + (-a) = 0
        if isinstance(right, UnaryOp) and right.op == "-":
            if _expr_equal(left, right.operand):
                return Num(0)
        # (-a) + a = 0
        if isinstance(left, UnaryOp) and left.op == "-":
            if _expr_equal(left.operand, right):
                return Num(0)
    return None


def _identity_sub(left: Any, right: Any, enabled_rules: set[str]) -> Any | None:
    """Algebraic identities for subtraction: a-0, a-a, 0-a."""
    if "subtract_zero" in enabled_rules:
        # a - 0 = a
        if isinstance(right, Num) and right.value == 0:
            return left
    if "subtract_self" in enabled_rules:
        # a - a = 0
        if _expr_equal(left, right):
            return Num(0)
    # 0 - a = -a (part of additive identity)
    if "additive_identity" in enabled_rules:
        if isinstance(left, Num) and left.value == 0:
            return UnaryOp("-", right)
    return None


def _identity_mul(left: Any, right: Any, enabled_rules: set[str]) -> Any | None:
    """Algebraic identities for multiplication: a*0, a*1, a*(-1)."""
    if "multiplicative_zero" in enabled_rules:
        # a * 0 = 0
        if isinstance(right, Num) and right.value == 0:
            return Num(0)
        if isinstance(left, Num) and left.value == 0:
            return Num(0)
    if "multiplicative_identity" in enabled_rules:
        # a * 1 = a
        if isinstance(right, Num) and right.value == 1:
            return left
        # 1 * a = a
        if isinstance(left, Num) and left.value == 1:
            return right
    if "multiplicative_inverse" in enabled_rules:
        # a * (-1) = -a
        if isinstance(right, Num) and right.value == -1:
            return UnaryOp("-", left)
        if isinstance(left, Num) and left.value == -1:
            return UnaryOp("-", right)
    return None


def _identity_div(left: Any, right: Any, enabled_rules: set[str]) -> Any | None:
    """Algebraic identities for division: a/1, 0/a, a/a."""
    if "divide_identity" in enabled_rules:
        # a / 1 = a
        if isinstance(right, Num) and right.value == 1:
            return left
    if "divide_zero" in enabled_rules:
        # 0 / a = 0 (a ≠ 0)
        if isinstance(left, Num) and left.value == 0:
            if not (isinstance(right, Num) and right.value == 0):
                return Num(0)
    if "divide_self" in enabled_rules:
        # a / a = 1 (a ≠ 0)
        if _expr_equal(left, right):
            # Don't simplify 0/0 — it's undefined
            if isinstance(left, Num) and left.value == 0:
                return None
            return Num(1)
    return None


def _identity_pow(left: Any, right: Any, enabled_rules: set[str]) -> Any | None:
    """Algebraic identities for exponentiation: a^0, a^1, 0^a, 1^a."""
    if "power_zero" in enabled_rules:
        # a ^ 0 = 1
        if isinstance(right, Num) and right.value == 0:
            return Num(1)
    if "power_one" in enabled_rules:
        # a ^ 1 = a
        if isinstance(right, Num) and right.value == 1:
            return left
    if "zero_power" in enabled_rules:
        # 0 ^ a = 0 (a > 0)
        if isinstance(left, Num) and left.value == 0:
            if isinstance(right, Num) and right.value > 0:
                return Num(0)
    if "one_power" in enabled_rules:
        # 1 ^ a = 1
        if isinstance(left, Num) and left.value == 1:
            return Num(1)
    return None


def _expr_equal(a: Any, b: Any) -> bool:
    """Check if two expression trees are structurally equal."""
    if type(a) is not type(b):
        return False
    if isinstance(a, Num):
        return a.value == b.value
    if isinstance(a, Var):
        return a.name == b.name
    if isinstance(a, BinOp):
        return a.op == b.op and _expr_equal(a.left, b.left) and _expr_equal(a.right, b.right)
    if isinstance(a, UnaryOp):
        return a.op == b.op and _expr_equal(a.operand, b.operand)
    if isinstance(a, FuncCall):
        return (
            a.name == b.name
            and len(a.args) == len(b.args)
            and all(_expr_equal(x, y) for x, y in zip(a.args, b.args, strict=True))
        )
    return False


def _term_key(node: Any) -> str:
    """Generate a canonical string key for a term, ignoring order.

    For example, a*b and b*a both produce the same key.
    """
    if isinstance(node, Num):
        return f"num:{node.value}"
    if isinstance(node, Var):
        return f"var:{node.name}"
    if isinstance(node, BinOp):
        if node.op == "*":
            # Multiplication is commutative — sort factors
            factors = _flatten_factors(node)
            return "mul:" + ",".join(sorted(factors))
        if node.op == "+":
            return "add:" + _term_key(node.left) + "," + _term_key(node.right)
        return f"binop:{node.op}:{_term_key(node.left)},{_term_key(node.right)}"
    if isinstance(node, UnaryOp):
        return f"unary:{node.op}:{_term_key(node.operand)}"
    if isinstance(node, FuncCall):
        return f"func:{node.name}:{','.join(_term_key(a) for a in node.args)}"
    return str(node)


def _flatten_factors(node: Any) -> list[str]:
    """Flatten a multiplication tree into a list of factor keys."""
    if isinstance(node, BinOp) and node.op == "*":
        return _flatten_factors(node.left) + _flatten_factors(node.right)
    return [_term_key(node)]


def _collect_terms(node: Any) -> Any:
    """Collect like terms in a sum.

    Converts a*a + a*b + b*a + b*b into a*a + 2*a*b + b*b by
    combining terms with the same factors (using commutativity).
    """
    if not isinstance(node, BinOp):
        return node

    # Recursively collect sub-expressions first
    left = _collect_terms(node.left)
    right = _collect_terms(node.right)
    node = BinOp(node.op, left, right)

    if node.op != "+":
        return node

    # Flatten the sum into a list of terms
    terms = _flatten_sum(node)

    # Group terms by their factor signature (ignoring numeric coefficient)
    grouped: dict[str, list[Any]] = {}
    coefficients: dict[str, float] = {}
    term_order: list[str] = []

    for term in terms:
        coeff, factors = _extract_coeff_and_factors(term)
        key = ",".join(sorted(factors))
        if key not in grouped:
            grouped[key] = []
            coefficients[key] = 0.0
            term_order.append(key)
        grouped[key].append(term)
        coefficients[key] += coeff

    # Rebuild the sum with collected coefficients
    result_terms: list[Any] = []
    for key in term_order:
        coeff = coefficients[key]
        if coeff == 0:
            continue
        # Get the factor part from the first term in the group
        _, factors = _extract_coeff_and_factors(grouped[key][0])
        if not factors:
            # Pure constant term
            result_terms.append(Num(coeff))
        elif coeff == 1:
            # Just the factors, no coefficient
            result_terms.append(_build_product(factors))
        else:
            # Coefficient * factors
            result_terms.append(BinOp("*", Num(coeff), _build_product(factors)))

    if not result_terms:
        return Num(0)
    if len(result_terms) == 1:
        return result_terms[0]

    # Build the sum
    result = result_terms[0]
    for term in result_terms[1:]:
        result = BinOp("+", result, term)
    return result


def _flatten_sum(node: Any) -> list[Any]:
    """Flatten an addition tree into a list of terms."""
    if isinstance(node, BinOp) and node.op == "+":
        return _flatten_sum(node.left) + _flatten_sum(node.right)
    return [node]


def _extract_coeff_and_factors(node: Any) -> tuple[float, list[str]]:
    """Extract the numeric coefficient and factor keys from a term.

    For example, 3*a*b → (3.0, ["var:a", "var:b"])
    a*b → (1.0, ["var:a", "var:b"])
    5 → (5.0, [])
    """
    if isinstance(node, Num):
        return (float(node.value), [])
    if isinstance(node, Var):
        return (1.0, [_term_key(node)])
    if isinstance(node, BinOp) and node.op == "*":
        left_coeff, left_factors = _extract_coeff_and_factors(node.left)
        right_coeff, right_factors = _extract_coeff_and_factors(node.right)
        return (left_coeff * right_coeff, left_factors + right_factors)
    if isinstance(node, BinOp) and node.op == "^":
        # var^n → factor is "var^n"
        return (1.0, [_term_key(node)])
    if isinstance(node, UnaryOp) and node.op == "-":
        coeff, factors = _extract_coeff_and_factors(node.operand)
        return (-coeff, factors)
    return (1.0, [_term_key(node)])


def _build_product(factors: list[str]) -> Any:
    """Build a product expression from a list of factor keys."""
    if not factors:
        return Num(1)
    # Convert factor keys back to simple expressions
    # This is simplified — just use Var for var: keys
    nodes: list[Any] = []
    for f in factors:
        if f.startswith("var:"):
            nodes.append(Var(f[4:]))
        elif f.startswith("num:"):
            val = f[4:]
            try:
                nodes.append(Num(float(val)))
            except ValueError:
                nodes.append(Var(f))
        else:
            # Complex factor — use as-is via a placeholder
            nodes.append(Var(f))
    if len(nodes) == 1:
        return nodes[0]
    result = nodes[0]
    for n in nodes[1:]:
        result = BinOp("*", result, n)
    return result


def _expr_to_str(node: Any) -> str:
    """Convert an expression tree to a readable string."""
    if isinstance(node, Num):
        return format_number(node.value)
    if isinstance(node, Var):
        return node.name
    if isinstance(node, BinOp):
        left = _expr_to_str(node.left)
        right = _expr_to_str(node.right)
        # Add parens for clarity when needed
        if isinstance(node.left, BinOp) and _PRECEDENCE_OF.get(
            node.left.op, 0
        ) < _PRECEDENCE_OF.get(node.op, 0):
            left = f"({left})"
        if isinstance(node.right, BinOp) and _PRECEDENCE_OF.get(
            node.right.op, 0
        ) < _PRECEDENCE_OF.get(node.op, 0):
            right = f"({right})"
        return f"{left} {node.op} {right}"
    if isinstance(node, UnaryOp):
        return f"-{_expr_to_str(node.operand)}"
    if isinstance(node, FuncCall):
        return f"{node.name}({_expr_to_str(node.args[0]) if node.args else ''})"
    return str(node)


_PRECEDENCE_OF = {"+": 2, "-": 2, "*": 3, "/": 3, "^": 4}


@dataclass
class SolveStep:
    """A single step in a solution."""

    description: str
    expression: str


@dataclass
class SolveResult:
    """Result of solving an equation."""

    solution: str
    steps: list[SolveStep] = field(default_factory=list)
    variable: str = ""
    success: bool = True


def _solve_early_return(
    all_vars: set[str], eq: Equation, steps: list[SolveStep]
) -> SolveResult | None:
    """Handle the no-variable and multi-variable cases before solving.

    Returns a SolveResult for the trivial cases (no variables → evaluate
    both sides; multiple variables → cannot solve), or None to let the
    caller proceed with single-variable solving.
    """
    if len(all_vars) == 0:
        # No variables — just evaluate both sides
        try:
            left_val = evaluate(eq.left)
            right_val = evaluate(eq.right)
            if abs(left_val - right_val) < 1e-10:
                return SolveResult("True", steps, "", True)
            return SolveResult("False", steps, "", True)
        except EvalError:
            return SolveResult("Cannot evaluate", steps, "", False)
    if len(all_vars) > 1:
        return SolveResult(
            f"Cannot solve — multiple variables: {', '.join(sorted(all_vars))}",
            steps,
            "",
            False,
        )
    return None


def solve_equation(eq: Equation, enabled_rules: set[str] | None = None) -> SolveResult:
    """Solve a linear or quadratic equation for its variable.

    Uses transformation rules (balance, isolate, simplify) applied
    mechanically by the engine. The simplification rules are gated by
    ``enabled_rules`` (see ``simplify()`` for the rule names). The
    steps are recorded so Genesis can explain its reasoning.
    """
    steps: list[SolveStep] = []

    # Find the variable to solve for
    all_vars = collect_variables(eq.left) | collect_variables(eq.right)
    early = _solve_early_return(all_vars, eq, steps)
    if early is not None:
        return early

    var_name = all_vars.pop()
    steps.append(
        SolveStep(
            f"Solve for {var_name}",
            _expr_to_str(eq.left) + f" {eq.comparator} " + _expr_to_str(eq.right),
        )
    )

    # Move everything to the left side: left - right = 0
    left = simplify(BinOp("-", eq.left, eq.right), enabled_rules)
    steps.append(
        SolveStep(
            "Move all terms to one side",
            f"{_expr_to_str(left)} = 0",
        )
    )

    # Expand and collect terms
    expanded = _expand(left)
    expanded = simplify(expanded, enabled_rules)
    expanded = _normalize_powers(expanded)
    steps.append(
        SolveStep(
            "Simplify",
            f"{_expr_to_str(expanded)} = 0",
        )
    )

    # Classify: linear (a*x + b) or quadratic (a*x^2 + b*x + c)
    coeffs = _extract_coefficients(expanded, var_name)

    if coeffs is None:
        return SolveResult(
            f"Cannot solve — expression too complex: {_expr_to_str(expanded)} = 0",
            steps,
            var_name,
            False,
        )

    degree = max(k for k in coeffs if k > 0) if any(k > 0 for k in coeffs) else 0

    if degree == 1:
        return _solve_linear(coeffs, var_name, steps)

    if degree == 2:
        return _solve_quadratic(coeffs, var_name, steps)

    return SolveResult(
        f"Cannot solve — degree {degree} equations not supported",
        steps,
        var_name,
        False,
    )


def _solve_linear(
    coeffs: dict[int, float], var_name: str, steps: list[SolveStep]
) -> SolveResult:
    """Solve a linear equation a*x + b = 0 → x = -b/a."""
    # Linear: a*x + b = 0 → x = -b/a
    a = coeffs.get(1, 0)
    b = coeffs.get(0, 0)
    if a == 0:
        if b == 0:
            return SolveResult("Infinite solutions (identity)", steps, var_name, True)
        return SolveResult("No solution (contradiction)", steps, var_name, True)
    solution = -b / a
    steps.append(
        SolveStep(
            f"Divide both sides by {format_number(a)}",
            f"{var_name} = {format_number(-b)} / {format_number(a)}",
        )
    )
    result = format_number(solution)
    steps.append(
        SolveStep(
            "Compute the result",
            f"{var_name} = {result}",
        )
    )
    return SolveResult(f"{var_name} = {result}", steps, var_name, True)


def _solve_quadratic(
    coeffs: dict[int, float], var_name: str, steps: list[SolveStep]
) -> SolveResult:
    """Solve a quadratic a*x^2 + b*x + c = 0 via the quadratic formula."""
    # Quadratic: a*x^2 + b*x + c = 0 → quadratic formula
    a = coeffs.get(2, 0)
    b = coeffs.get(1, 0)
    c = coeffs.get(0, 0)
    if a == 0:
        # Degenerate — treat as linear
        if b == 0:
            if c == 0:
                return SolveResult("Infinite solutions", steps, var_name, True)
            return SolveResult("No solution", steps, var_name, True)
        solution = -c / b
        return SolveResult(f"{var_name} = {format_number(solution)}", steps, var_name, True)

    discriminant = b * b - 4 * a * c
    steps.append(
        SolveStep(
            "Apply the quadratic formula",
            f"{var_name} = ({-b} ± sqrt({b}^2 - 4*{a}*{c})) / (2*{a})",
        )
    )
    steps.append(
        SolveStep(
            "Compute the discriminant",
            f"discriminant = {format_number(discriminant)}",
        )
    )

    if discriminant > 0:
        sqrt_d = math.sqrt(discriminant)
        x1 = (-b + sqrt_d) / (2 * a)
        x2 = (-b - sqrt_d) / (2 * a)
        result = f"{var_name} = {format_number(x1)} or {var_name} = {format_number(x2)}"
        steps.append(
            SolveStep(
                "Two real solutions",
                result,
            )
        )
        return SolveResult(result, steps, var_name, True)
    elif discriminant == 0:
        x = -b / (2 * a)
        result = f"{var_name} = {format_number(x)}"
        steps.append(
            SolveStep(
                "One real solution (repeated root)",
                result,
            )
        )
        return SolveResult(result, steps, var_name, True)
    else:
        real_part = -b / (2 * a)
        imag_part = math.sqrt(-discriminant) / (2 * a)
        result = (
            f"{var_name} = {format_number(real_part)} + {format_number(imag_part)}i "
            f"or {var_name} = {format_number(real_part)} - {format_number(imag_part)}i"
        )
        steps.append(
            SolveStep(
                "Two complex solutions",
                result,
            )
        )
        return SolveResult(result, steps, var_name, True)


def _expand(node: Any) -> Any:
    """Expand an expression by distributing multiplication over addition
    and expanding small integer exponents."""
    if isinstance(node, BinOp):
        left = _expand(node.left)
        right = _expand(node.right)

        if node.op == "*":
            # (a + b) * c → a*c + b*c
            if isinstance(left, BinOp) and left.op in ("+", "-"):
                return BinOp(
                    left.op,
                    _expand(BinOp("*", left.left, right)),
                    _expand(BinOp("*", left.right, right)),
                )
            # a * (b + c) → a*b + a*c
            if isinstance(right, BinOp) and right.op in ("+", "-"):
                return BinOp(
                    right.op,
                    _expand(BinOp("*", left, right.left)),
                    _expand(BinOp("*", left, right.right)),
                )

        if node.op == "^":
            # Expand (a + b)^n for small integer n by repeated multiplication
            if isinstance(right, Num) and isinstance(right.value, int) and 2 <= right.value <= 4:
                n = right.value
                # Build the product by repeated multiplication
                result = left
                for _ in range(n - 1):
                    result = BinOp("*", result, _expand(left))
                return _expand(result)
            # Also handle float exponents that are integers
            if (
                isinstance(right, Num)
                and isinstance(right.value, float)
                and right.value.is_integer()
                and 2 <= right.value <= 4
            ):
                n = int(right.value)
                result = left
                for _ in range(n - 1):
                    result = BinOp("*", result, _expand(left))
                return _expand(result)

        return BinOp(node.op, left, right)

    if isinstance(node, UnaryOp):
        return UnaryOp(node.op, _expand(node.operand))

    if isinstance(node, FuncCall):
        return FuncCall(node.name, [_expand(a) for a in node.args])

    return node


def _normalize_powers(node: Any) -> Any:
    """Convert repeated multiplication of the same variable into powers.

    For example, x * x → x^2, x * x * x → x^3.
    """
    if isinstance(node, BinOp):
        left = _normalize_powers(node.left)
        right = _normalize_powers(node.right)

        if node.op == "*":
            # Collect all factors
            factors = _flatten_mul(left) + _flatten_mul(right)
            # Group by variable name
            var_counts: dict[str, int] = {}
            other_factors: list[Any] = []
            for f in factors:
                if isinstance(f, Var):
                    var_counts[f.name] = var_counts.get(f.name, 0) + 1
                else:
                    other_factors.append(f)
            # Rebuild with powers
            result_factors: list[Any] = []
            for var_name, count in var_counts.items():
                if count == 1:
                    result_factors.append(Var(var_name))
                else:
                    result_factors.append(BinOp("^", Var(var_name), Num(count)))
            result_factors.extend(other_factors)

            if not result_factors:
                return Num(1)
            if len(result_factors) == 1:
                return result_factors[0]
            result = result_factors[0]
            for f in result_factors[1:]:
                result = BinOp("*", result, f)
            return result

        return BinOp(node.op, left, right)

    if isinstance(node, UnaryOp):
        return UnaryOp(node.op, _normalize_powers(node.operand))

    if isinstance(node, FuncCall):
        return FuncCall(node.name, [_normalize_powers(a) for a in node.args])

    return node


def _flatten_mul(node: Any) -> list[Any]:
    """Flatten a multiplication tree into a list of factors."""
    if isinstance(node, BinOp) and node.op == "*":
        return _flatten_mul(node.left) + _flatten_mul(node.right)
    return [node]


def _extract_coefficients(node: Any, var: str) -> dict[int, float] | None:
    """Extract polynomial coefficients from an expression.

    Returns a dict {degree: coefficient} or None if the expression
    is not a polynomial in the given variable.
    """
    coeffs: dict[int, float] = {}

    def add_term(degree: int, coeff: float) -> None:
        """Accumulate *coeff* into the *degree* coefficient."""
        coeffs[degree] = coeffs.get(degree, 0) + coeff

    def extract(n: Any, sign: float = 1.0) -> bool:
        """Recursively extract polynomial terms from node *n*."""
        if isinstance(n, Num):
            add_term(0, sign * n.value)
            return True
        if isinstance(n, Var):
            if n.name == var:
                add_term(1, sign)
                return True
            # Other variables — can't handle
            return False
        if isinstance(n, UnaryOp) and n.op == "-":
            return extract(n.operand, -sign)
        if isinstance(n, BinOp):
            if n.op == "+":
                return extract(n.left, sign) and extract(n.right, sign)
            if n.op == "-":
                return extract(n.left, sign) and extract(n.right, -sign)
            if n.op == "*":
                return _extract_multiplication(n, var, sign, add_term)
            if n.op == "^":
                return _extract_power(n, var, sign, add_term)
            if n.op == "/":
                return _extract_division(n, var, sign, add_term)
        return False

    if extract(node):
        return coeffs
    return None


def _extract_multiplication(
    n: Any, var: str, sign: float, add_term
) -> bool:
    """Extract coefficients from a multiplication BinOp (constant × polynomial).

    One side must be a constant, the other a polynomial term in ``var``.
    Returns True if successfully extracted, False otherwise.
    """
    # One side must be a constant, the other a polynomial term
    left_coeffs = _try_constant(n.left)
    right_coeffs = _try_constant(n.right)
    if left_coeffs is not None:
        # constant * polynomial
        sub = _extract_coefficients(n.right, var)
        if sub is None:
            return False
        for deg, coef in sub.items():
            add_term(deg, sign * left_coeffs * coef)
        return True
    if right_coeffs is not None:
        sub = _extract_coefficients(n.left, var)
        if sub is None:
            return False
        for deg, coef in sub.items():
            add_term(deg, sign * right_coeffs * coef)
        return True
    return False


def _extract_power(n: Any, var: str, sign: float, add_term) -> bool:
    """Extract coefficients from an exponentiation BinOp (var^int or const^int).

    Handles ``var ^ integer`` (adds a term of that degree) and
    ``constant ^ integer`` (evaluates and adds a degree-0 term).
    Returns True if successfully extracted, False otherwise.
    """
    # var ^ integer
    if isinstance(n.left, Var) and n.left.name == var and isinstance(n.right, Num):
        exp = n.right.value
        if isinstance(exp, int) or (isinstance(exp, float) and exp.is_integer()):
            add_term(int(exp), sign)
            return True
    # constant ^ integer
    if isinstance(n.left, Num) and isinstance(n.right, Num):
        try:
            val = evaluate(n)
            add_term(0, sign * val)
            return True
        except EvalError:
            return False
    return False


def _extract_division(n: Any, var: str, sign: float, add_term) -> bool:
    """Extract coefficients from a division BinOp (polynomial ÷ constant).

    The divisor must be a non-zero constant. Returns True if
    successfully extracted, False otherwise.
    """
    # polynomial / constant
    divisor = _try_constant(n.right)
    if divisor is not None and divisor != 0:
        sub = _extract_coefficients(n.left, var)
        if sub is None:
            return False
        for deg, coef in sub.items():
            add_term(deg, sign * coef / divisor)
        return True
    return False


def _try_constant(node: Any) -> float | None:
    """Try to evaluate a node as a constant (no variables)."""
    if not collect_variables(node):
        try:
            return evaluate(node)
        except EvalError:
            return None
    return None


