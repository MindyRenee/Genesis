@dataclass
class MathResult:
    """Result of a math reasoning operation."""

    answer: str
    result_type: str  # "computation", "solution", "proof", "discovery"
    steps: list[str] = field(default_factory=list)
    success: bool = True


def _math_fragment(lower: str) -> str:
    """Extract the mathematical fragment of a question, dropping the
    natural-language shell so 'what is' doesn't read as variables."""
    for pattern in (
        r"(?:what\s+is|what's|calculate|compute|evaluate)\s+(.+)",
        r"(?:solve|find\s+x\s+in|find\s+the\s+value\s+of\s+x\s+in)\s+(.+)",
        r"(?:discover|find\s+patterns?\s+in|explore|investigate)\s+(.+)",
    ):
        match = re.match(pattern, lower)
        if match:
            return match.group(1).rstrip("?").strip()
    return lower


def _math_state(question: str) -> dict[str, Any]:
    """Structural signature of a math question.

    Operators, arity, and form are schema-level structure; the literal
    numbers are bindings — '2 + 3' and '5 + 7' are the same task
    wearing different values.
    """
    lower = question.lower().strip()
    fragment = _math_fragment(lower)
    tokens = tokenize(fragment)
    numbers = sum(1 for t in tokens if t.type == TokenType.NUMBER)
    idents = {t.value for t in tokens if t.type == TokenType.IDENT}
    functions = idents & _BUILTIN_FUNCTIONS.keys()
    variables = idents - _BUILTIN_FUNCTIONS.keys() - {
        "pi",
        "e",
        "infinity",
    }
    ops = {
        t.value
        for t in tokens
        if t.type
        in (
            TokenType.PLUS,
            TokenType.MINUS,
            TokenType.STAR,
            TokenType.SLASH,
            TokenType.CARET,
        )
    }
    has_eq = any(
        t.type
        in (
            TokenType.EQ,
            TokenType.LT,
            TokenType.GT,
            TokenType.LE,
            TokenType.GE,
            TokenType.NE,
        )
        for t in tokens
    )
    if lower.startswith(("prove ", "show that ")):
        form = "prove"
    elif re.match(
        r"(?:discover|find\s+patterns?\s+in|explore|investigate)\s", lower
    ):
        form = "discover"
    elif re.match(
        r"(?:solve|find\s+x\s+in|find\s+the\s+value\s+of\s+x\s+in)\s", lower
    ):
        form = "solve"
    elif re.match(
        r"(?:what\s+is|what's|calculate|compute|evaluate)\s", lower
    ):
        form = "compute"
    else:
        form = "expression"
    state: dict[str, Any] = {
        "math.form": form,
        "math.equation": has_eq,
        "math.numbers": min(numbers, 5),
        "math.variables": min(len(variables), 3),
        "math.functions": min(len(functions), 3),
    }
    for op in sorted(ops):
        state[f"math.op:{op}"] = True
    return state


def _record_math_episode(
    task_competence: Any,
    question: str,
    result: MathResult,
    salience: float | None,
) -> None:
    """Consolidate a math episode into the shared competence substrate.

    The math engine's own evaluation is the check, so verification is
    ``"solver"`` — honest provenance, not an external claim. Failed
    results record schema failures without consolidating a skill.
    Recognition runs *after* dispatch so non-math questions never
    litter the schema store.
    """
    from .competence import GoalCondition, ProcedureStep

    goal = GoalCondition("math.answered", "eq", 1)
    context = task_competence.recognize(
        domain="math",
        state=_math_state(question),
        goal_conditions=[goal],
        roles=("symbolic", "exact"),
    )
    steps = [
        ProcedureStep(
            action=result.result_type,
            family=result.result_type,
            description=step,
        )
        for step in result.steps
    ]
    if not steps:
        steps = [
            ProcedureStep(
                action=result.result_type,
                family=result.result_type,
                description=result.answer,
            )
        ]
    task_competence.record_episode(
        context,
        steps=steps,
        success=result.success,
        verification_score=1.0 if result.success else 0.0,
        goal_conditions=[goal],
        verification="solver",
        salience=salience,
    )


def try_math(
    question: str,
    network: Any = None,
    task_competence: Any = None,
    salience: float | None = None,
) -> MathResult | None:
    """Try to answer a question using mathematical reasoning.

    This is the entry point for the cognition engine. It detects
    what kind of math question is being asked and routes it to
    the appropriate engine (computation, solving, proof, discovery).

    If a concept network is provided, the simplification rules are
    gated by what Genesis has learned (see ``MathRuleRegistry``).
    Without a concept network, all rules are enabled (backward
    compatible).

    When ``task_competence`` is provided, each answered question is
    recorded as an episode: schemas accumulate which math families
    succeed or fail, and verified results consolidate as skills the
    concept network can reason about.

    Returns None if the question is not a math question.
    """
    lower = question.lower().strip()

    # Build rule registry from concept network if available
    enabled_rules: set[str] | None = None
    if network is not None:
        registry = MathRuleRegistry.from_concept_network(network)
        enabled_rules = registry.enabled_rules

    result = (
        # ── Computation: "what is 2 + 2?" ──
        _try_compute(lower, enabled_rules)
        # ── Bare expression: "2 + 2", "sqrt(16)" ──
        or _try_bare_expression(lower)
        # ── Equation solving: "solve 2x = 6" ──
        or _try_solve(lower, enabled_rules)
        # ── Proof requests: "prove that ..." ──
        or _try_proof(question, lower)
        # ── Discovery: "discover patterns in primes" ──
        or _try_discover(lower)
    )
    if result is not None and task_competence is not None:
        _record_math_episode(task_competence, question, result, salience)
    return result


def _try_compute(lower: str, enabled_rules: set[str] | None) -> MathResult | None:
    """Detect 'what is 2 + 2' style computation requests."""
    # Look for arithmetic expressions
    compute_match = re.match(
        r"(?:what\s+is|what's|calculate|compute|evaluate)\s+(.+)",
        lower,
    )
    if compute_match:
        expr_str = compute_match.group(1).rstrip("?")
        # Don't treat definitions as computations
        if not _looks_like_definition(expr_str):
            try:
                parsed = parse_expression(expr_str)
                if isinstance(parsed, Equation):
                    # It's an equation — try to solve or verify
                    result = solve_equation(parsed, enabled_rules)
                    if result.success:
                        return MathResult(
                            result.solution,
                            "solution",
                            [f"{s.description}: {s.expression}" for s in result.steps],
                        )
                else:
                    # It's an expression — evaluate it
                    value = evaluate(parsed)
                    return MathResult(
                        f"{format_number(value)}",
                        "computation",
                        [f"{_expr_to_str(parsed)} = {format_number(value)}"],
                    )
            except (ParseError, EvalError) as e:
                logger.debug(repr(e))
    return None


def _try_bare_expression(lower: str) -> MathResult | None:
    """Detect bare arithmetic expressions like '2 + 2', 'sqrt(16)'."""
    if re.match(r"^[\d\s+\-*/^().,a-z_]+[?]?$", lower):
        expr_str = lower.rstrip("?").strip()
        if any(c.isdigit() for c in expr_str) and any(c in "+-*/^" for c in expr_str):
            try:
                parsed = parse_expression(expr_str)
                if isinstance(parsed, (BinOp, UnaryOp, FuncCall, Num)):
                    value = evaluate(parsed)
                    return MathResult(
                        f"{format_number(value)}",
                        "computation",
                        [f"{_expr_to_str(parsed)} = {format_number(value)}"],
                    )
            except (ParseError, EvalError) as e:
                logger.debug(repr(e))
    return None


def _try_solve(lower: str, enabled_rules: set[str] | None) -> MathResult | None:
    """Detect equation-solving requests like 'solve 2x = 6'."""
    solve_match = re.match(
        r"(?:solve|find\s+x\s+in|find\s+the\s+value\s+of\s+x\s+in)\s+(.+)",
        lower,
    )
    if solve_match:
        eq_str = solve_match.group(1).rstrip("?")
        try:
            parsed = parse_expression(eq_str)
            if isinstance(parsed, Equation):
                result = solve_equation(parsed, enabled_rules)
                if result.success:
                    return MathResult(
                        result.solution,
                        "solution",
                        [f"{s.description}: {s.expression}" for s in result.steps],
                    )
        except (ParseError, EvalError) as e:
            logger.debug(repr(e))
    return None


def _try_proof(question: str, lower: str) -> MathResult | None:
    """Detect proof requests like 'prove that ...'."""
    if lower.startswith("prove ") or lower.startswith("show that "):
        result = prove(question)
        return MathResult(
            result.conclusion,
            "proof",
            [f"{s.statement} ({s.justification})" for s in result.steps],
            result.success,
        )
    return None


def _try_discover(lower: str) -> MathResult | None:
    """Detect discovery requests like 'discover patterns in primes'."""
    discover_match = re.match(
        r"(?:discover|find\s+patterns?\s+in|explore|investigate)\s+(.+)",
        lower,
    )
    if discover_match:
        topic = discover_match.group(1).rstrip("?")
        result = discover(topic)
        return MathResult(
            result.summary,
            "discovery",
            [],
            len(result.conjectures) > 0,
        )
    return None


def _looks_like_definition(text: str) -> bool:
    """Check if text looks like a definition rather than a computation.

    "what is calculus" is a definition, "what is 2+2" is a computation.
    """
    # If it has digits and operators, it's likely a computation
    has_digits = any(c.isdigit() for c in text)
    has_ops = any(c in "+-*/^=" for c in text)
    if has_digits and has_ops:
        return False
    # If it has no digits, it's likely a definition
    if not has_digits:
        return True
    # If it has digits but no operators, could be either
    return False
