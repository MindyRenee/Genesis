# Built-in functions — these are the computational substrate.
# Which functions exist is learned (stored in concept network as
# concepts like "sine", "cosine", "square root"). The actual
# computation is performed by the engine, like neurons firing.
_BUILTIN_FUNCTIONS: dict[str, Callable[..., Any]] = {
    "sqrt": math.sqrt,
    "abs": abs,
    "sin": math.sin,
    "cos": math.cos,
    "tan": math.tan,
    "log": math.log,
    "ln": math.log,
    "log10": math.log10,
    "log2": math.log2,
    "exp": math.exp,
    "floor": math.floor,
    "ceil": math.ceil,
    "round": round,
    "factorial": lambda n: math.factorial(int(n)),
    "gcd": lambda a, b: math.gcd(int(a), int(b)),
    "max": max,
    "min": min,
    "mod": lambda a, b: a % b,
    "pow": pow,
}


class EvalError(Exception):
    """Raised when an expression cannot be evaluated."""

    pass


def evaluate(node: Any, env: dict[str, float] | None = None) -> float | int:
    """Evaluate an expression tree to a numeric value.

    Args:
        node: AST node (Num, Var, BinOp, UnaryOp, FuncCall)
        env: variable bindings (name → value)

    Returns:
        Numeric result

    Raises:
        EvalError: if the expression can't be evaluated (unbound variable, etc.)
    """
    if env is None:
        env = {}

    if isinstance(node, Num):
        return node.value

    if isinstance(node, Var):
        if node.name in env:
            return env[node.name]
        raise EvalError(f"Unbound variable: {node.name}")

    if isinstance(node, UnaryOp):
        val = evaluate(node.operand, env)
        if node.op == "-":
            return -val
        return val

    if isinstance(node, BinOp):
        left = evaluate(node.left, env)
        right = evaluate(node.right, env)
        if node.op == "+":
            return left + right
        if node.op == "-":
            return left - right
        if node.op == "*":
            return left * right
        if node.op == "/":
            if right == 0:
                raise EvalError("Division by zero")
            return left / right
        if node.op == "^":
            try:
                return left**right
            except (OverflowError, ValueError, ZeroDivisionError) as e:
                raise EvalError(f"Cannot evaluate power: {e}") from e
        raise EvalError(f"Unknown operator: {node.op}")

    if isinstance(node, FuncCall):
        if node.name not in _BUILTIN_FUNCTIONS:
            raise EvalError(f"Unknown function: {node.name}")
        args = [evaluate(a, env) for a in node.args]
        try:
            return _BUILTIN_FUNCTIONS[node.name](*args)
        except (ValueError, OverflowError, ZeroDivisionError) as e:
            raise EvalError(f"Cannot evaluate {node.name}: {e}") from e

    raise EvalError(f"Cannot evaluate node type: {type(node).__name__}")


def format_number(n: float | int) -> str:
    """Format a number nicely for display."""
    if isinstance(n, float):
        if n.is_integer() and abs(n) < 1e15:
            return str(int(n))
        if math.isinf(n):
            return "infinity" if n > 0 else "-infinity"
        # Round to reasonable precision
        return f"{n:.6g}"
    return str(n)


