class TokenType(Enum):
    """Types of tokens produced by the math expression tokenizer."""

    NUMBER = "number"
    IDENT = "ident"  # variable or function name
    PLUS = "+"
    MINUS = "-"
    STAR = "*"
    SLASH = "/"
    CARET = "^"
    LPAREN = "("
    RPAREN = ")"
    EQ = "="
    LT = "<"
    GT = ">"
    LE = "<="
    GE = ">="
    NE = "!="
    COMMA = ","
    EOF = "eof"


@dataclass(slots=True)
class Token:
    """A single token from the math expression tokenizer."""

    type: TokenType
    value: str
    pos: int


_SINGLE_CHAR_OPS = {
    "+": TokenType.PLUS,
    "-": TokenType.MINUS,
    "*": TokenType.STAR,
    "/": TokenType.SLASH,
    "^": TokenType.CARET,
    "(": TokenType.LPAREN,
    ")": TokenType.RPAREN,
    "=": TokenType.EQ,
    "<": TokenType.LT,
    ">": TokenType.GT,
    ",": TokenType.COMMA,
}

_MULTI_CHAR_OPS = {
    "<=": TokenType.LE,
    ">=": TokenType.GE,
    "!=": TokenType.NE,
    "==": TokenType.EQ,
}


def _scan_number(text: str, i: int, tokens: list[Token]) -> int:
    """Scan a numeric literal (with scientific notation) and append a NUMBER token.

    Also inserts an implicit-multiplication STAR when the number is
    immediately followed by a variable/function name.
    Returns the new scan index.
    """
    start = i
    while i < len(text) and (text[i].isdigit() or text[i] == "."):
        i += 1
    # Scientific notation
    if i < len(text) and text[i] in "eE":
        j = i + 1
        if j < len(text) and text[j] in "+-":
            j += 1
        if j < len(text) and text[j].isdigit():
            i = j
            while i < len(text) and text[i].isdigit():
                i += 1
    tokens.append(Token(TokenType.NUMBER, text[start:i], start))
    # Insert implicit multiplication: number followed by
    # variable or function (e.g., "2x" → "2 * x", "3sin" → "3 * sin")
    if i < len(text) and (text[i].isalpha() or text[i] == "_"):
        tokens.append(Token(TokenType.STAR, "*", i))
    return i


def _scan_ident(text: str, i: int, tokens: list[Token]) -> int:
    """Scan an identifier (variable/function name) and append an IDENT token.

    Inserts an implicit-multiplication STAR when the identifier is
    immediately followed by another variable or a number (but NOT
    before "(", which is a function call). Returns the new scan index.
    """
    start = i
    while i < len(text) and (text[i].isalnum() or text[i] == "_"):
        i += 1
    tokens.append(Token(TokenType.IDENT, text[start:i], start))
    # Insert implicit multiplication: variable followed by
    # number or another variable (e.g., "x2" → "x * 2",
    # "xy" → "x * y"). But NOT before "(" — that's a
    # function call (e.g., "sqrt(...)", "sin(...)"), not
    # multiplication.
    if i < len(text) and (text[i].isalnum() or text[i] == "_"):
        if text[i].isalpha() or text[i] == "_":
            # Variable followed by variable: x*y
            tokens.append(Token(TokenType.STAR, "*", i))
        elif text[i].isdigit():
            # Variable followed by number: x*2
            tokens.append(Token(TokenType.STAR, "*", i))
    return i


def tokenize(text: str) -> list[Token]:
    """Convert a math expression string into tokens."""
    tokens: list[Token] = []
    i = 0
    text = text.replace("×", "*").replace("÷", "/").replace("−", "-")
    # Handle sqrt(), abs(), etc. — keep function names as idents
    while i < len(text):
        c = text[i]
        if c.isspace():
            i += 1
            continue
        # Multi-character operators
        if text[i : i + 2] in _MULTI_CHAR_OPS:
            op = text[i : i + 2]
            tokens.append(Token(_MULTI_CHAR_OPS[op], op, i))
            i += 2
            continue
        # Single-character operators
        if c in _SINGLE_CHAR_OPS:
            tokens.append(Token(_SINGLE_CHAR_OPS[c], c, i))
            i += 1
            continue
        # Numbers (integers, decimals, fractions like 3/4 handled by parser)
        if c.isdigit() or (c == "." and i + 1 < len(text) and text[i + 1].isdigit()):
            i = _scan_number(text, i, tokens)
            continue
        # Identifiers (variables, function names, constants)
        if c.isalpha() or c == "_":
            i = _scan_ident(text, i, tokens)
            continue
        # Unknown character — skip it
        i += 1
    tokens.append(Token(TokenType.EOF, "", len(text)))
    return tokens


# AST node types
@dataclass
class Num:
    """AST node for a numeric literal."""

    value: float | int

    def __str__(self) -> str:
        """Render the numeric literal, dropping a trailing ``.0`` for floats."""
        if isinstance(self.value, float) and self.value.is_integer():
            return str(int(self.value))
        return str(self.value)


@dataclass
class Var:
    """AST node for a variable reference."""

    name: str

    def __str__(self) -> str:
        """Render the variable name."""
        return self.name


@dataclass
class BinOp:
    """AST node for a binary operation."""

    op: str  # +, -, *, /, ^
    left: Any
    right: Any

    def __str__(self) -> str:
        """Render the binary operation as ``left op right``."""
        return f"{self.left} {self.op} {self.right}"


@dataclass
class UnaryOp:
    """AST node for a unary operation."""

    op: str  # -, +
    operand: Any

    def __str__(self) -> str:
        """Render the unary operation as ``op operand``."""
        return f"{self.op}{self.operand}"


@dataclass
class FuncCall:
    """AST node for a function call."""

    name: str
    args: list[Any]

    def __str__(self) -> str:
        """Render the function call as ``name(arg, ...)``."""
        return f"{self.name}({', '.join(str(a) for a in self.args)})"


@dataclass
class Equation:
    """AST node for an equation or comparison."""

    left: Any
    right: Any
    comparator: str  # =, <, >, <=, >=, !=

    def __str__(self) -> str:
        """Render the equation as ``left comparator right``."""
        return f"{self.left} {self.comparator} {self.right}"


class ParseError(Exception):
    """Raised when the parser encounters invalid syntax."""

    pass


class Parser:
    """Recursive descent parser for mathematical expressions and equations."""

    # Operator precedence (higher = binds tighter)
    # Comparison operators (=, <, >, etc.) are NOT here — they're
    # handled by parse() to create Equation nodes, not BinOp nodes.
    _PRECEDENCE: ClassVar[dict] = {
        TokenType.PLUS: 2,
        TokenType.MINUS: 2,
        TokenType.STAR: 3,
        TokenType.SLASH: 3,
        TokenType.CARET: 4,
    }

    def __init__(self, tokens: list[Token]) -> None:
        """Initialize the math expression parser."""
        self.tokens = tokens
        self.pos = 0

    def peek(self) -> Token:
        """Return the current token without consuming it."""
        return self.tokens[self.pos]

    def advance(self) -> Token:
        """Consume and return the current token, advancing to the next."""
        t = self.tokens[self.pos]
        self.pos += 1
        return t

    def expect(self, tt: TokenType) -> Token:
        """Consume the current token if it matches *tt*, else raise ParseError."""
        t = self.peek()
        if t.type != tt:
            raise ParseError(f"Expected {tt.value}, got {t.value!r} at pos {t.pos}")
        return self.advance()

    def parse(self) -> Equation | Any:
        """Parse a full expression or equation."""
        left = self._parse_expr(0)

        t = self.peek()
        if t.type in (
            TokenType.EQ,
            TokenType.LT,
            TokenType.GT,
            TokenType.LE,
            TokenType.GE,
            TokenType.NE,
        ):
            comp = t.value
            self.advance()
            right = self._parse_expr(0)
            return Equation(left, right, comp)

        return left

    def _parse_expr(self, min_prec: int) -> Any:
        """Parse an expression with operator precedence (Pratt parsing)."""
        left = self._parse_unary()

        while True:
            t = self.peek()
            prec = self._PRECEDENCE.get(t.type, 0)
            if prec < min_prec or prec == 0:
                break
            op = t.value
            self.advance()
            right = self._parse_expr(prec + 1)
            left = BinOp(op, left, right)

        return left

    def _parse_unary(self) -> Any:
        """Parse a unary expression (leading +/- or primary)."""
        t = self.peek()
        if t.type == TokenType.MINUS:
            self.advance()
            operand = self._parse_unary()
            return UnaryOp("-", operand)
        if t.type == TokenType.PLUS:
            self.advance()
            return self._parse_unary()
        return self._parse_primary()

    def _parse_primary(self) -> Any:
        """Parse a primary expression (number, variable, parenthesized)."""
        t = self.peek()

        if t.type == TokenType.NUMBER:
            self.advance()
            raw = t.value
            if "." in raw or "e" in raw or "E" in raw:
                return Num(float(raw))
            return Num(int(raw))

        if t.type == TokenType.IDENT:
            self.advance()
            name = t.value
            # Check for function call
            if self.peek().type == TokenType.LPAREN:
                self.advance()  # consume (
                args: list[Any] = []
                if self.peek().type != TokenType.RPAREN:
                    args.append(self._parse_expr(0))
                    while self.peek().type == TokenType.COMMA:
                        self.advance()
                        args.append(self._parse_expr(0))
                self.expect(TokenType.RPAREN)
                return FuncCall(name, args)
            # Named constants
            if name.lower() == "pi":
                return Num(math.pi)
            if name.lower() == "e":
                return Num(math.e)
            if name.lower() == "infinity":
                return Num(math.inf)
            return Var(name)

        if t.type == TokenType.LPAREN:
            self.advance()
            expr = self._parse_expr(0)
            self.expect(TokenType.RPAREN)
            return expr

        raise ParseError(f"Unexpected token {t.value!r} at pos {t.pos}")


def parse_expression(text: str) -> Equation | Any:
    """Parse a math expression or equation from text."""
    tokens = tokenize(text)
    parser = Parser(tokens)
    return parser.parse()


