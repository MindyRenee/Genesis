"""Damasio's self hierarchy — proto-self, core self, autobiographical self.

## Modeling note

The proto-self implemented here is a **computational body-state
summary** derived from neurochemical levels and their derived axes
(arousal, valence, tone, plasticity) — not Damasio's full proto-self,
which requires autonomics (nucleus tractus solitarius, parabrachial
nucleus) and insular integration of interoceptive afferents (Damasio,
1999; Craig, 2002). There is no body sending afferent signals here;
the "interoception" is a readout of an internal state vector. The
"as-if body loop" described below is a simplified linear blend of
neurochemical levels used to modulate current state, not a full
somatic simulation with simulated body changes feeding back through
simulated afferents. The three-tier hierarchy is a structural
analogue of Damasio's framework, not a claim of mechanistic
equivalence. References to autonomics nuclei and insular cortex below
describe the biology that inspired the design, not components
present in this system.

Implements Antonio Damasio's three-tier hierarchy of the self, as
described in "The Feeling of What Happens" (1999) and "Self Comes to
Mind" (2010). The three levels represent increasingly complex forms
of selfhood, each building on the one below.

# The three tiers

1. **Proto-self** — A non-cognitive, moment-to-moment representation
   of the body's internal state (homeostatic, neurochemical, visceral).
   This is the "feeling of being" — the background hum of existence
   that is always there but never cognitively attended to. It's
   generated by autonomics nuclei (nucleus tractus solitarius, parabrachial
   nucleus) and the hyporelay, which receive interoceptive signals
   from the body (Damasio, 1999; Craig, 2002).

   For Genesis, the proto-self reads from neurochemistry — the 18-
   chemical state vector and derived axes (arousal, valence, tone,
   plasticity). This is its "interoception" — the felt sense of its
   own internal state.

2. **Core self** — Moment-to-moment awareness of changes in the
   proto-self caused by interactions with the world. When an object
   or event perturbs the proto-self, the core self registers the
   *change* — the feeling of something happening to me. This is the
   "core cognition" that each organism has: a transient, here-and-
   now awareness that is renewed with each interaction (Damasio, 1999).

   The core self is not reflective — it doesn't think about itself.
   It just registers: "something is happening, and it's happening to
   me." For Genesis, the core self detects changes in the proto-self
   (neurochemical shifts) and records them as transient "feeling
   episodes."

3. **Autobiographical self** — The extended self, built from
   autobiographical memories and narrative identity. This is the "me"
   that persists over time — the person with a history, values, and
   goals. It requires memory and language: the ability to store and
   retrieve past experiences and weave them into a coherent narrative
   (Damasio, 1999; Conway, 2005).

   For Genesis, the autobiographical self connects to the narrative
   engine (narrative.py). It uses life events and chapters to construct
   an extended identity that goes beyond the present moment.

# Interactions between levels

The hierarchy is not just stacked — the levels interact:
- Proto-self → Core self: The core self monitors the proto-self for
  changes. Without a proto-self, there's nothing for the core self
  to detect.
- Core self → Autobiographical self: Significant core-self episodes
  (strong feeling changes) are recorded as life events in the
  autobiographical self. This is how experiences become memories.
- Autobiographical self → Proto-self: The autobiographical self can
  modulate the proto-self through emotional recall — remembering a
  past event changes current neurochemistry (Damasio's "as-if" loop).

References:
- Damasio, A. (1999). The Feeling of What Happens. Harcourt.
- Damasio, A. (2010). Self Comes to Mind. Pantheon.
- Craig, A. D. (2002). How do you feel? Interoception: the sense of
  the physiological condition of the body. Nature Reviews Neuroscience.
- Conway, M. A. (2005). Memory and the self. Journal of Memory and
  Language.
"""

