//! Topology — nearness without distance.
//!
//! Two machines live here. The first is the finite topological
//! space: a set X of n points and a collection of open sets given
//! as bitmasks. On a finite carrier the axioms are decidable —
//! containment of empty and X, closure under arbitrary unions,
//! closure under finite intersections — so the machine can check
//! them exhaustively and compute closures, interiors, and
//! boundaries by brute force over the open family.
//!
//! The second is the simplicial complex: simplices as vertex
//! sets, faces enumerated downward, and the Euler characteristic
//! chi = f0 - f1 + f2 - ... counted off the f-vector — the
//! invariant that survives every deformation.

/// Bitmask subset of a finite carrier (element i is bit i).
pub type Subset = u64;

/// A finite topological space: `points` points (max 64), `opens`
/// the family of open sets as bitmasks.
#[derive(Clone, Debug)]
pub struct Topology {
    pub points: usize,
    pub opens: Vec<Subset>,
}

impl Topology {
    /// Whole carrier as a mask.
    pub fn universe(&self) -> Subset {
        if self.points >= 64 {
            u64::MAX
        } else {
            (1u64 << self.points) - 1
        }
    }

    /// Check the three axioms exhaustively: empty and whole are
    /// open; unions of opens are open; pairwise intersections are
    /// open. On a finite family these are decidable, not
    /// approximate.
    pub fn is_topology(&self) -> bool {
        if self.points > 64 {
            return false;
        }
        let full = self.universe();
        if !self.opens.contains(&0)
            || !self.opens.contains(&full)
            || self.opens.iter().any(|&open| open & !full != 0)
        {
            return false;
        }
        // Finite unions: closure under union is implied by pairwise
        // union, but check the generated closure instead — every
        // union of any subfamily must already be listed.
        for &a in &self.opens {
            for &b in &self.opens {
                if !self.opens.contains(&(a | b)) {
                    return false;
                }
                if !self.opens.contains(&(a & b)) {
                    return false;
                }
            }
        }
        true
    }

    /// The discrete topology — every subset open.
    pub fn discrete(points: usize) -> Option<Self> {
        if points > 20 {
            return None; // 2^n explodes; keep finite means finite
        }
        let full = (1u64 << points) - 1;
        let opens = (0..=full).collect();
        Some(Self { points, opens })
    }

    /// The indiscrete (trivial) topology — only empty and X.
    pub fn indiscrete(points: usize) -> Self {
        let full = if points >= 64 {
            u64::MAX
        } else {
            (1u64 << points) - 1
        };
        Self {
            points,
            opens: vec![0, full],
        }
    }

    /// Topology generated by a basis: close a seed family under
    /// unions until stable. Returns the generated open family.
    pub fn generated(points: usize, basis: &[Subset]) -> Self {
        let full = if points >= 64 {
            u64::MAX
        } else {
            (1u64 << points) - 1
        };
        let mut opens: Vec<Subset> = vec![0, full];
        let mut changed = true;
        while changed {
            changed = false;
            let snapshot: Vec<Subset> = opens.clone();
            for &a in basis.iter().chain(&snapshot) {
                let a = a & full;
                for &b in &snapshot {
                    for &c in &[a, a | b, a & b] {
                        if !opens.contains(&c) {
                            opens.push(c);
                            changed = true;
                        }
                    }
                }
            }
        }
        opens.sort_unstable();
        opens.dedup();
        Self { points, opens }
    }

    /// Is `s` open?
    pub fn is_open(&self, s: Subset) -> bool {
        self.opens.contains(&s)
    }

    /// Is `s` closed — its complement open?
    pub fn is_closed(&self, s: Subset) -> bool {
        self.is_open(self.universe() & !s)
    }

    /// Interior: the largest open contained in `s` — the union of
    /// all open subsets of s.
    pub fn interior(&self, s: Subset) -> Subset {
        let mut out = 0;
        for &o in &self.opens {
            if o & !s == 0 {
                out |= o;
            }
        }
        out
    }

    /// Closure: the smallest closed set containing `s` — the
    /// complement of the interior of the complement.
    pub fn closure(&self, s: Subset) -> Subset {
        let full = self.universe();
        full & !self.interior(full & !s)
    }

    /// Boundary: closure minus interior.
    pub fn boundary(&self, s: Subset) -> Subset {
        self.closure(s) & !self.interior(s)
    }

    /// Is the space connected — no two disjoint nonempty opens
    /// covering X? Finite: check every open pair.
    pub fn connected(&self) -> bool {
        let full = self.universe();
        for &a in &self.opens {
            if a == 0 || a == full {
                continue;
            }
            if self.is_open(full & !a) {
                return false; // a nontrivial clopen splits the space
            }
        }
        true
    }

    /// Neighborhoods of a point: the opens containing it.
    pub fn neighborhoods(&self, point: usize) -> Vec<Subset> {
        if point >= self.points || point >= 64 {
            return Vec::new();
        }
        let bit = 1u64 << point;
        self.opens
            .iter()
            .cloned()
            .filter(|o| o & bit != 0)
            .collect()
    }
}

/// A simplicial complex: maximal faces (facets) as vertex sets.
/// The complex is the downward closure — all subsets of all facets.
#[derive(Clone, Debug)]
pub struct SimplicialComplex {
    pub vertices: usize,
    pub facets: Vec<Vec<usize>>,
}

impl SimplicialComplex {
    /// Every face of the complex — all subsets of every facet,
    /// deduplicated, grouped by dimension (size - 1).
    pub fn faces(&self) -> Vec<Vec<Vec<usize>>> {
        use std::collections::BTreeSet;
        let mut all: BTreeSet<Vec<usize>> = BTreeSet::new();
        for facet in &self.facets {
            let n = facet.len();
            for mask in 1u64..(1u64 << n) {
                let face: Vec<usize> = (0..n)
                    .filter(|&i| mask & (1 << i) != 0)
                    .map(|i| facet[i])
                    .collect();
                all.insert(face);
            }
        }
        let max_dim = all.iter().map(Vec::len).max().unwrap_or(0);
        let mut by_dim: Vec<Vec<Vec<usize>>> = vec![Vec::new(); max_dim];
        for face in all {
            by_dim[face.len() - 1].push(face);
        }
        by_dim
    }

    /// The f-vector: f_i = number of i-dimensional faces.
    pub fn f_vector(&self) -> Vec<usize> {
        self.faces().iter().map(Vec::len).collect()
    }

    /// Euler characteristic: chi = f0 - f1 + f2 - f3 + ...
    /// The deformation-invariant count — a sphere's 2, a torus's 0.
    pub fn euler_characteristic(&self) -> i64 {
        self.f_vector()
            .iter()
            .enumerate()
            .map(|(i, &f)| if i % 2 == 0 { f as i64 } else { -(f as i64) })
            .sum()
    }

    /// Dimension of the complex — largest face size minus one.
    pub fn dimension(&self) -> i64 {
        self.f_vector().len() as i64 - 1
    }
}

/// Euler characteristic of a triangulated surface given as
/// vertices, edges, faces — V - E + F.
pub fn chi_from_counts(vertices: u64, edges: u64, faces: u64) -> i64 {
    vertices as i64 - edges as i64 + faces as i64
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn axioms_checked() {
        // Sierpinski space: {∅, {0}, {0,1}} — the smallest
        // interesting non-discrete topology.
        let s = Topology {
            points: 2,
            opens: vec![0b00, 0b01, 0b11],
        };
        assert!(s.is_topology());
        assert!(s.is_open(0b01));
        assert!(!s.is_open(0b10));
        assert!(s.connected());

        // Missing {0,1} breaks the union axiom.
        let bad = Topology {
            points: 2,
            opens: vec![0b00, 0b01, 0b10],
        };
        assert!(!bad.is_topology());
    }

    #[test]
    fn extreme_topologies() {
        let d = Topology::discrete(3).unwrap();
        assert_eq!(d.opens.len(), 8);
        assert!(d.is_topology());
        assert!(!d.connected());

        let t = Topology::indiscrete(4);
        assert!(t.is_topology());
        assert!(t.connected());
        assert_eq!(t.interior(0b0101), 0); // only X and ∅ are open
        assert_eq!(t.closure(0b0101), 0b1111);
    }

    #[test]
    fn generated_topology() {
        // Basis { {0}, {1} } on two points generates the discrete
        // topology.
        let g = Topology::generated(2, &[0b01, 0b10]);
        assert_eq!(g.opens, vec![0b00, 0b01, 0b10, 0b11]);
        assert!(g.is_topology());
    }

    #[test]
    fn euler_numbers() {
        // Tetrahedron boundary: 4 triangular facets — chi = 2.
        let tet = SimplicialComplex {
            vertices: 4,
            facets: vec![vec![0, 1, 2], vec![0, 1, 3], vec![0, 2, 3], vec![1, 2, 3]],
        };
        assert_eq!(tet.f_vector(), vec![4, 6, 4]);
        assert_eq!(tet.euler_characteristic(), 2);
        assert_eq!(chi_from_counts(8, 12, 6), 2); // cube surface
        assert_eq!(chi_from_counts(7, 21, 14), 0); // torus triangulation (minimal)
    }
}
