//! Abstract algebra — the algebra of structure itself.
//!
//! Groups are where the machine's mathematics meets play: a
//! permutation is a move, composition is doing one then the next,
//! and the order of an element is the length of the closed orbit —
//! run the move `order` times and you are home. Rubik's turns are
//! permutations on 54 facelets; this module computes their group.

use std::collections::BTreeSet;

/// A permutation of {0, .., n-1}, stored as images: `image[i]` is
/// where element i goes.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Permutation {
    pub image: Vec<usize>,
}

impl Permutation {
    /// Build from an image list; None if it isn't a bijection.
    pub fn new(image: Vec<usize>) -> Option<Self> {
        let n = image.len();
        let mut seen = vec![false; n];
        for &j in &image {
            if j >= n || seen[j] {
                return None;
            }
            seen[j] = true;
        }
        Some(Self { image })
    }

    /// The identity on n points.
    pub fn identity(n: usize) -> Self {
        Self {
            image: (0..n).collect(),
        }
    }

    /// A single cycle (a b c …) sending a→b, b→c, last→first.
    pub fn cycle(n: usize, cycle: &[usize]) -> Option<Self> {
        if cycle.is_empty() || cycle.iter().any(|&x| x >= n) {
            return None;
        }
        let mut p = Self::identity(n);
        for w in cycle.windows(2) {
            p.image[w[0]] = w[1];
        }
        let &last = cycle.last()?;
        p.image[last] = cycle[0];
        Some(p)
    }

    /// Composition — `self` then `other`: x ↦ `other[self[x]]`.
    /// Written `self * other` reading moves left to right.
    pub fn then(&self, other: &Permutation) -> Option<Permutation> {
        if self.image.len() != other.image.len() {
            return None;
        }
        Some(Permutation {
            image: self.image.iter().map(|&j| other.image[j]).collect(),
        })
    }

    /// The inverse permutation.
    pub fn inverse(&self) -> Permutation {
        let mut inv = vec![0; self.image.len()];
        for (i, &j) in self.image.iter().enumerate() {
            inv[j] = i;
        }
        Permutation { image: inv }
    }

    /// True when every point is fixed.
    pub fn is_identity(&self) -> bool {
        self.image.iter().enumerate().all(|(i, &j)| i == j)
    }

    /// Order of the element — least k > 0 with pᵏ = e. This is
    /// the closed orbit's length: the move repeated `order` times
    /// returns every point home.
    pub fn order(&self) -> u64 {
        self.cycles()
            .iter()
            .map(|c| c.len() as u64)
            .fold(1, crate::math::number_theory::lcm)
    }

    /// Cycle decomposition — disjoint cycles covering every point,
    /// fixed points listed as 1-cycles.
    pub fn cycles(&self) -> Vec<Vec<usize>> {
        let n = self.image.len();
        let mut seen = vec![false; n];
        let mut out = Vec::new();
        for start in 0..n {
            if seen[start] {
                continue;
            }
            let mut cyc = vec![start];
            seen[start] = true;
            let mut x = self.image[start];
            while x != start {
                cyc.push(x);
                seen[x] = true;
                x = self.image[x];
            }
            out.push(cyc);
        }
        out
    }

    /// Sign: +1 even, -1 odd. A k-cycle contributes (-1)^(k-1).
    pub fn sign(&self) -> i64 {
        let parity: usize = self.cycles().iter().map(|c| c.len() - 1).sum();
        if parity % 2 == 0 { 1 } else { -1 }
    }

    /// Iterate pᵏ(x) — the orbit of one element under the move.
    pub fn orbit_of(&self, x: usize) -> Option<Vec<usize>> {
        if x >= self.image.len() {
            return None;
        }
        let mut out = vec![x];
        let mut y = self.image[x];
        while y != x {
            out.push(y);
            y = self.image[y];
        }
        Some(out)
    }
}

/// The subgroup generated by a move set — closure under
/// composition, bounded to `cap` elements. Returns the element
/// images when the closure stays under the cap.
pub fn generated_subgroup(generators: &[Permutation], cap: usize) -> Option<Vec<Permutation>> {
    if generators.is_empty() {
        return Some(vec![]);
    }
    let n = generators[0].image.len();
    if generators.iter().any(|g| g.image.len() != n) {
        return None;
    }
    let id = Permutation::identity(n);
    let mut seen: BTreeSet<Vec<usize>> = [id.image.clone()].into_iter().collect();
    let mut group = vec![id];
    let mut queue: Vec<Permutation> = generators.to_vec();
    while let Some(g) = queue.pop() {
        if !seen.insert(g.image.clone()) {
            continue;
        }
        if group.len() >= cap {
            return None; // too big to hold — the honest overflow
        }
        // Multiply g by everything already known, both sides.
        for h in group.clone() {
            for next in [g.then(&h), h.then(&g)].into_iter().flatten() {
                if !seen.contains(&next.image) {
                    queue.push(next);
                }
            }
        }
        group.push(g);
    }
    Some(group)
}

/// ℤₙ — the additive cyclic group. Order of element a in ℤₙ.
pub fn zn_order(a: u64, n: u64) -> Option<u64> {
    if n == 0 || a >= n {
        return None;
    }
    if a == 0 {
        return Some(1);
    }
    Some(n / crate::math::number_theory::gcd(a, n))
}

/// ℤₙˣ — the multiplicative group of units mod n.
pub fn units_mod(n: u64) -> Vec<u64> {
    (1..n)
        .filter(|&a| crate::math::number_theory::gcd(a, n) == 1)
        .collect()
}

/// Cayley table of ℤₙ addition.
pub fn zn_add_table(n: u64) -> Option<Vec<Vec<u64>>> {
    if n == 0 || n > 512 {
        return None;
    }
    Some(
        (0..n)
            .map(|a| (0..n).map(|b| (a + b) % n).collect())
            .collect(),
    )
}

/// Is the map φ: ℤₙ → ℤₘ (given as images φ(k)) a homomorphism?
/// Checks φ(a+b) = φ(a)+φ(b) at every pair — finite means
/// decidable.
pub fn is_homomorphism_zn(images: &[u64], n: u64, m: u64) -> bool {
    if images.len() as u64 != n || m == 0 || images.iter().any(|&x| x >= m) {
        return false;
    }
    for a in 0..n {
        for b in 0..n {
            let lhs = images[((a + b) % n) as usize];
            let rhs = (images[a as usize] + images[b as usize]) % m;
            if lhs != rhs {
                return false;
            }
        }
    }
    true
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cycles_and_order() {
        // (0 1 2)(3 4) — order lcm(3,2) = 6
        let p = Permutation::new(vec![1, 2, 0, 4, 3]).unwrap();
        assert_eq!(p.order(), 6);
        assert_eq!(p.cycles().len(), 2);
        assert_eq!(p.sign(), -1); // 3-cycle(2 trans)·transposition(1) → odd
    }

    #[test]
    fn compose_inverse() {
        let p = Permutation::cycle(4, &[0, 1, 2]).unwrap();
        let q = Permutation::cycle(4, &[1, 3]).unwrap();
        let pq = p.then(&q).unwrap();
        let qp = q.then(&p).unwrap();
        assert!(pq.then(&qp.inverse()).is_some());
        assert!(p.then(&p.inverse()).unwrap().is_identity());
    }

    #[test]
    fn closed_orbit() {
        // The cube pattern: a repeated move pair returns home.
        // u then d then u then d ... u^4 = e for a 4-cycle.
        let u = Permutation::cycle(4, &[0, 1, 2, 3]).unwrap();
        let mut acc = Permutation::identity(4);
        for _ in 0..4 {
            acc = acc.then(&u).unwrap();
        }
        assert!(acc.is_identity());
        assert_eq!(u.order(), 4);
    }

    #[test]
    fn klein_four() {
        // ℤ₂×ℤ₂: three order-2 elements, closed — generated by
        // two commuting transpositions.
        let a = Permutation::cycle(4, &[0, 1]).unwrap();
        let b = Permutation::cycle(4, &[2, 3]).unwrap();
        let g = generated_subgroup(&[a, b], 16).unwrap();
        assert_eq!(g.len(), 4);
    }

    #[test]
    fn zn_arith() {
        assert_eq!(zn_order(2, 6), Some(3));
        assert_eq!(units_mod(8), vec![1, 3, 5, 7]);
        assert!(is_homomorphism_zn(&[0, 2, 4, 6], 4, 8));
        assert!(!is_homomorphism_zn(&[0, 1, 4, 6], 4, 8));
    }
}
